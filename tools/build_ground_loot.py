"""Developer-only x86 assembler; shipped helper uses the generated stdlib image."""
from pathlib import Path
import re,struct
from keystone import Ks,KS_ARCH_X86,KS_MODE_32
from capstone import Cs,CS_ARCH_X86,CS_MODE_32,CS_GRP_CALL,CS_GRP_JUMP
from capstone.x86 import X86_OP_MEM,X86_OP_IMM
ROOT=Path(__file__).resolve().parents[1]
BASE=0x10000000;DATA=0x2000;SIZE=0x3000
source=(ROOT/'tools/native/ground_loot.asm').read_text('utf8')
sections=re.split(r'^;; @section (\w+) (0x[0-9a-f]+)\s*$',source,flags=re.M)
names={sections[i]:int(sections[i+1],16) for i in range(1,len(sections),3)}
ks=Ks(KS_ARCH_X86,KS_MODE_32);md=Cs(CS_ARCH_X86,CS_MODE_32);md.detail=True
raw=bytearray(DATA);relocations=[]
for i in range(1,len(sections),3):
    name,offset,body=sections[i:i+3];offset=int(offset,16)
    body=re.sub(r';[^\n]*','',body).replace('@data',hex(BASE+DATA))
    for symbol,value in names.items():body=re.sub('@'+symbol+r'\b',hex(BASE+value),body)
    code=bytes(ks.asm(body,BASE+offset)[0]);assert offset+len(code)<=DATA
    assert not any(raw[offset:offset+len(code)]),(name,'overlap')
    raw[offset:offset+len(code)]=code
    for ins in md.disasm(code,BASE+offset):
        rel=ins.address-BASE
        for op in ins.operands:
            if op.type==X86_OP_MEM and BASE<=op.mem.disp<BASE+SIZE:
                assert ins.disp_size==4;relocations.append((rel+ins.disp_offset,1))
            elif op.type==X86_OP_IMM:
                branch=ins.group(CS_GRP_CALL) or ins.group(CS_GRP_JUMP)
                if branch and not BASE<=op.imm<BASE+SIZE:
                    assert ins.imm_size==4;relocations.append((rel+ins.imm_offset,-1))
                elif not branch and BASE<=op.imm<BASE+SIZE:
                    assert ins.imm_size==4;relocations.append((rel+ins.imm_offset,1))
    print(name,hex(offset),len(code))
out='"""Generated by tools/build_ground_loot.py from tools/native/ground_loot.asm."""\nimport struct\n'
out+=f'BASE={BASE}\nDATA={DATA}\nSIZE={SIZE}\nOFFSETS={names!r}\nRELOCATIONS={relocations!r}\n'
out+='CODE=bytes.fromhex(\n'+''.join('    '+repr(raw.hex()[n:n+120])+'\n' for n in range(0,len(raw)*2,120))+')\n'
out+='\ndef image(base):\n    raw=bytearray(SIZE);raw[:len(CODE)]=CODE\n    for at,sign in RELOCATIONS:\n        value=struct.unpack_from("<I",raw,at)[0]\n        struct.pack_into("<I",raw,at,(value+sign*(base-BASE))&0xffffffff)\n    return raw\n'
(ROOT/'app/ground_loot_core.py').write_text(out,'utf8')
