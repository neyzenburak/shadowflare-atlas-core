'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {JSDOM}=require('jsdom');
const root=path.resolve(__dirname,'../app');
const dom=new JSDOM(fs.readFileSync(path.join(root,'index.html'),'utf8'),{url:'http://localhost/',runScripts:'outside-only'});
const w=dom.window,d=w.document,requests=[];
w.HTMLElement.prototype.scrollIntoView=function(){};
w.AtlasLive={request:async(endpoint,body)=>{requests.push({endpoint,body});return{version:3,active:body.enabled?['atlas-blackjack']:[],frozen:[],undoCount:0,values:{}};},refresh:async()=>{}};
for(const file of ['trainer-data.js','trainer-extras.js','trainer.js'])w.eval(fs.readFileSync(path.join(root,file),'utf8'));
const state=version=>w.dispatchEvent(new w.CustomEvent('atlas:live-state',{detail:{connected:true,ready:true,protocol:19,pid:10,player:100,trainer:{version,active:[],frozen:[]}}}));
const button=()=>d.querySelector('[data-toggle="atlas-blackjack"]');
(async()=>{
  assert(button(),'Blackjack must be visible in the cheats group');assert(button().disabled);
  state(1);assert(button().disabled,'old helper must not accept a new toggle');assert(button().title.includes('yeniden'));
  state(3);assert.equal(button().disabled,false);
  button().click();await new Promise(r=>setTimeout(r,20));
  assert(requests.some(r=>r.endpoint==='/api/trainer/toggle'&&r.body.id==='atlas-blackjack'&&r.body.enabled===true));
  assert.equal(button().getAttribute('aria-checked'),'true');
  button().click();await new Promise(r=>setTimeout(r,20));
  assert(requests.some(r=>r.endpoint==='/api/trainer/toggle'&&r.body.enabled===false));
  assert.equal(button().getAttribute('aria-checked'),'false');
  const input=d.getElementById('trainerSearch');input.value='blackjack';input.dispatchEvent(new w.Event('input'));
  assert(button());assert(d.getElementById('trainerRecords').textContent.includes('K + A'));
  assert(d.getElementById('trainerRecords').textContent.includes('beraberlik'));
  assert.equal(w.TRAINER_DATA.records.some(r=>r.id==='atlas-blackjack'),false,'original CT data stays separate');
  console.log('PASS: Blackjack trainer discovery, helper compatibility, toggle requests, status and search');
  dom.window.close();
})().catch(error=>{console.error(error);dom.window.close();process.exitCode=1;});
